function inyo(strokes){
  const s = strokes.map(n=>n%2); // 1=陽(奇数) 0=陰(偶数)
  const pat = s.map(v=>v?'○':'●').join('');
  let b=0; for(let i=1;i<s.length;i++) if(s[i]!==s[i-1]) b++;
  let rating, name, text;
  if(b===0){
    rating='凶'; name= s[0]?'純陽':'純陰';
    text='すべてが'+(s[0]?'陽（奇数・○）':'陰（偶数・●）')+'に偏った配列。片寄りから孤立や停滞を招きやすいとされます。呼び名や通称でやわらげる工夫も一法です。';
  } else if(b===1){
    let cut=1; while(s[cut]===s[0]) cut++;
    const len1=cut, len2=s.length-cut;
    if(s.length===2){
      rating='吉'; name='調和';
      text='陰と陽がひとつずつ並ぶ、素直で調和のとれた配列です。';
    } else if(len1>=2 && len2>=2){
      rating='凶'; name='二分';
      text='上下で陰と陽が真っ二つに分かれる〈二分〉の配列。内と外、前半と後半で明暗が分かれやすいとされます。数理の吉で補いましょう。';
    } else {
      rating='半吉'; name='片寄り';
      text='おおむね一方の気に寄りつつ、端で転じる配列。大きな乱れはありませんが、やや偏りがあります。';
    }
  } else {
    const mid = s.slice(1,-1);
    const sandwiched = s.length>=4 && s[0]===s[s.length-1] && mid.every(v=>v===mid[0]) && mid[0]!==s[0];
    if(sandwiched){
      rating='半吉'; name='挟み';
      text='両端が同じ気で中を挟む〈挟み〉の形。守りには強い一方、内にこもりやすい面があるとされます。';
    } else {
      rating='吉'; name='調和';
      text='陰陽がほどよく交じり合い、気の流れの滞らない良い配列です。';
    }
  }
  return {pattern:pat, rating, name, text};
}

