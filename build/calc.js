/* --- 文字の画数解決 --- */
const REPEAT={'々':0,'ゝ':0,'ヽ':0,'ゞ':2,'ヾ':2}; // 繰り返し記号（ゞ・ヾは濁点分+2）
function resolveChar(ch, opts, prev){
  const info = {ch, counted:ch, strokes:null, basis:[], known:true};
  if(REPEAT[ch]!=null){
    if(prev==null){ info.known=false; info.basis.push('直前の文字なし'); return info; }
    info.strokes=prev+REPEAT[ch];
    info.basis.push(REPEAT[ch]?'繰り返し（濁点 +'+REPEAT[ch]+'）':'繰り返し（直前と同数）');
    return info;
  }
  if(opts.suii && NUM[ch]!=null){
    info.strokes=NUM[ch]; info.basis.push('数意（'+NUM[ch]+'画）');
    return info;
  }
  const v = VAR[ch]||null;           // 異体字（髙→高 等）は数え方の設定に関わらず同字とみなす
  const base = v||ch;
  if(v) info.basis.push('「'+v+'」の異体字');
  const k = opts.kyu ? (KYU[base]||base) : base;
  info.counted = k;
  info.varOnly = v!=null && k===v;
  const raw = RAW[k];
  if(raw==null){ info.known=false; return info; }
  let s = raw;
  if(opts.bushu && ADJ[k]){ s += ADJ[k]; info.basis.push('部首補正 +'+ADJ[k]); }
  if(k!==base) info.basis.unshift('旧字体「'+k+'」で計上');
  info.strokes = s;
  return info;
}

/* --- 五格 --- */
function gokaku(sei, mei){ // 画数配列
  const sum=a=>a.reduce((x,y)=>x+y,0);
  const tenBase=sum(sei), chiBase=sum(mei);
  const ten = sei.length===1 ? tenBase+1 : tenBase;
  const chi = mei.length===1 ? chiBase+1 : chiBase;
  const jin = sei[sei.length-1] + mei[0];
  const sou = tenBase + chiBase;
  const gai = ten + chi - jin;
  return {
    ten: fortuneOf(ten), jin: fortuneOf(jin), chi: fortuneOf(chi),
    gai: fortuneOf(gai), sou: fortuneOf(sou),
    reiSei: sei.length===1, reiMei: mei.length===1
  };
}

